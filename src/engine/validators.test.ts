import { describe, expect, it } from 'vitest';
import { buildSampleWorkbook, R_KA, R_MH, SUPPLIER } from '../../scripts/sample-workbook';
import {
  checkGstr1Json, checkHsn, describeGstin, fixGstr1Json, generateGstr1Json, markAutoFixable, parseGstr1Tables, profileForPeriod, readWorkbook,
  type ReturnContext,
} from './index';

const ctx = (): ReturnContext => ({ supplierGstin: SUPPLIER, fp: '062025', aatoAbove5Cr: false, profile: profileForPeriod('062025') });
const today = new Date(Date.UTC(2025, 7, 1));

async function cleanJson() {
  const tables = await readWorkbook(await buildSampleWorkbook(false));
  const { records } = parseGstr1Tables(tables, { supplierGstin: SUPPLIER, hsnSplit: true });
  return generateGstr1Json(records, ctx()).json as Record<string, unknown>;
}

describe('HSN check', () => {
  it('accepts valid goods and service codes with descriptions', () => {
    expect(checkHsn('8471')).toMatchObject({ ok: true, kind: 'goods', chapterName: expect.stringContaining('Machinery') });
    expect(checkHsn('998314')).toMatchObject({ ok: true, kind: 'service', heading: '9983' });
    expect(checkHsn('8471.30 10').code).toBe('84713010');
  });
  it('rejects bad shape, chapters and SAC headings', () => {
    expect(checkHsn('84713').ok).toBe(false);
    expect(checkHsn('7701').ok).toBe(false);
    expect(checkHsn('0012').ok).toBe(false);
    expect(checkHsn('9950').ok).toBe(false);
    expect(checkHsn('84A1').ok).toBe(false);
  });
  it('applies the turnover band', () => {
    expect(checkHsn('8471', { aatoAbove5Cr: true }).ok).toBe(false);
    expect(checkHsn('8471', { aatoAbove5Cr: true, b2b: false }).ok).toBe(true);
    expect(checkHsn('847130', { aatoAbove5Cr: true }).ok).toBe(true);
  });
});

