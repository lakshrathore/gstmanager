    autoLiability: Mixed,
    autoFetchedAt: Date,
    portalForm: Mixed,
    portalDetails: Mixed,
    portalFetchedAt: Date,
    ledger: Mixed,
    ledgerFetchedAt: Date,
    fetchNotes: [String],
