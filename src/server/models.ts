/* Audit (append-only, hash-chained per org) */

const AuditLogSchema = new Schema({
  orgId: { type: ObjectId, required: true },
  seq: { type: Number, required: true },
  at: { type: Date, required: true },
  actorId: ObjectId,
  actorEmail: String,
  action: { type: String, required: true },
  entity: String,
  entityId: String,
  meta: Mixed,
  prevHash: String,
  hash: { type: String, required: true },
}, { minimize: false });
AuditLogSchema.index({ orgId: 1, seq: 1 }, { unique: true });
AuditLogSchema.index({ orgId: 1, entityId: 1, at: -1 });
const immutable = function () {
  throw new Error('Audit log is append-only');
};
for (const op of ['updateOne', 'updateMany', 'findOneAndUpdate', 'replaceOne', 'deleteOne', 'deleteMany', 'findOneAndDelete', 'findOneAndReplace'] as const) {
  AuditLogSchema.pre(op, immutable);
}

